"""Логотип владельца пиксель-артом для вывески на стене опенспейса (лицо стены — 24 ряда: логотип 21 + обводка + тень).

18.10, позже: «правил свой логотип» — новая картинка (2000×1299, 1,54:1): фигурные скобки, стержень из двух половин,
перемычка между ними касается их только углами, лучи «К» со срезанными плоско концами; штрих везде одинаковый — 160 точек
(здесь 3). Снято долей закраски по клеткам 33×21 (порог 0,5), клетки усреднены сверху-вниз; скобки зеркальны (столбец c ↔
32 − c). Рисуется верхняя половина (ряды 0–10), нижняя — отражение (21 ряд: середина — ряд 10). Первая версия (по картинке
до правки, 34×20) — в git офиса, ddf1b27.

    py pix/logo.py                  → печать
    py pix/logo.py <картинка>       → сверка с картинкой владельца по клеткам
"""
import sys

W, H = 33, 21


def top_half():
    spans = [
        # ряд: отрезки закрашенных столбцов (включительно)
        [(4, 6), (26, 28)],                     # 0  верх скобок (фаска)
        [(3, 6), (26, 29)],                     # 1
        [(2, 6), (26, 30)],                     # 2  низ верхних планок скобок
        [(2, 4), (28, 30)],                     # 3  скобки
        [(2, 4), (9, 11), (20, 22), (28, 30)],  # 4  верх половины стержня; плоский срез луча «К»
        [(2, 4), (9, 11), (19, 21), (28, 30)],  # 5
        [(2, 4), (9, 11), (18, 21), (28, 30)],  # 6
        [(2, 4), (9, 11), (17, 20), (28, 30)],  # 7
        [(1, 3), (9, 11), (17, 19), (29, 31)],  # 8  скобки к остриям; низ половины стержня
        [(0, 2), (12, 18), (30, 32)],           # 9  перемычка (касается стержня углом) и вершина «К»
        [(0, 2), (12, 18), (30, 32)],           # 10 середина: острия скобок
    ]
    rows = []
    for sp in spans:
        r = ['.'] * W
        for a, b in sp:
            for x in range(a, b + 1):
                r[x] = '#'
        rows.append(''.join(r))
    return rows


def logo_rows():
    t = top_half()
    return t + t[-2::-1]   # 0..10, потом 9..0


LOGO = logo_rows()
assert len(LOGO) == H and all(len(r) == W for r in LOGO)
assert all(LOGO[j][i] == LOGO[j][W - 1 - i] for j in range(H) for i in list(range(0, 8)) + list(range(25, 33)))   # скобки зеркальны

if __name__ == '__main__':
    for j, r in enumerate(LOGO):
        print('%2d %s' % (j, r))
    if len(sys.argv) > 1:   # сверка: доля закраски клетки на картинке (светлый логотип на белом — порог яркости 251)
        from PIL import Image
        src = Image.open(sys.argv[1]).convert('RGBA')
        im = Image.alpha_composite(Image.new('RGBA', src.size, (255, 255, 255, 255)), src).convert('L')
        px = im.load()
        X0, Y0, X1, Y1 = 0, 0, im.size[0], im.size[1]
        sx, sy = (X1 - X0) / W, (Y1 - Y0) / H
        agree = tot = 0
        worst = []
        for j in range(H):
            for i in range(W):
                n = d = 0
                for yy in range(int(Y0 + j * sy), min(Y1, int(Y0 + (j + 1) * sy))):
                    for xx in range(int(X0 + i * sx), min(X1, int(X0 + (i + 1) * sx)), 2):
                        n += 1
                        d += px[xx, yy] < 251
                c = d / n
                mine = LOGO[j][i] == '#'
                tot += 1
                agree += (c >= 0.5) == mine
                if (mine and c < 0.35) or (not mine and c > 0.65):
                    worst.append((j, i, round(c, 2), mine))
        print('совпадение клеток: %d из %d (%.1f %%)' % (agree, tot, agree * 100 / tot))
        print('явно мимо (рисунок против доли закраски):', worst)
