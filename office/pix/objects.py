class Canvas:
    def __init__(self, w, h):
        self.w, self.h = w, h
        self.a = [['.'] * w for _ in range(h)]

    def px(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.a[y][x] = c

    def rect(self, x, y, w, h, c):
        for j in range(y, y + h):
            for i in range(x, x + w):
                self.px(i, j, c)

    def rows(self):
        return [''.join(r) for r in self.a]

    def get(self, x, y):
        return self.a[y][x] if 0 <= x < self.w and 0 <= y < self.h else '.'

    def line(self, x0, y0, x1, y1, c, thick=1):
        """Отрезок Брезенхэма; thick 2 — с соседним пикселем справа и снизу."""
        dx, dy = abs(x1 - x0), -abs(y1 - y0)
        sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
        err = dx + dy
        while True:
            for j in range(thick):
                for i in range(thick):
                    self.px(x0 + i, y0 + j, c)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy; x0 += sx
            if e2 <= dx:
                err += dx; y0 += sy

    def ellipse(self, cx, cy, rx, ry, c):
        for j in range(-ry, ry + 1):
            for i in range(-rx, rx + 1):
                if (i / (rx + 0.5)) ** 2 + (j / (ry + 0.5)) ** 2 <= 1:
                    self.px(cx + i, cy + j, c)

    def shade(self, base, light, dark):
        """Светотень материала: край к свету (сверху-слева) — light, край от света — dark."""
        out = [r[:] for r in self.a]
        for y in range(self.h):
            for x in range(self.w):
                if self.a[y][x] != base:
                    continue
                if self.get(x - 1, y) in '.o' or self.get(x, y - 1) in '.o':
                    out[y][x] = light
                elif self.get(x + 1, y) in '.o' or self.get(x, y + 1) in '.o':
                    out[y][x] = dark
        self.a = out

    def outline(self, c='o'):
        """Обводка снаружи силуэта в пиксель — как у предметов Gemini."""
        out = [r[:] for r in self.a]
        for y in range(self.h):
            for x in range(self.w):
                if self.a[y][x] == '.' and any(self.get(x + i, y + j) not in '.' + c for i, j in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                    out[y][x] = c
        self.a = out


