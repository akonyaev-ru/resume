def _rrect(c, x, y, w, h, fill, top=True, bottom=True):
    """Прямоугольник в обводке со скруглёнными в две точки углами."""
    c.rect(x, y, w, h, 'o'); c.rect(x + 1, y + 1, w - 2, h - 2, fill)
    for cy, dy in ((y, 1), (y + h - 1, -1)):
        if (dy == 1 and not top) or (dy == -1 and not bottom):
            continue
        for cx, dx in ((x, 1), (x + w - 1, -1)):
            c.px(cx, cy, '.'); c.px(cx + dx, cy, '.'); c.px(cx, cy + dy, '.'); c.px(cx + dx, cy + dy, 'o')


