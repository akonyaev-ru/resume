def blob(c, pts, rib=()):
    """Лист или крона: обводка, свет сверху-слева, тень снизу-справа, светлая жилка по rib."""
    for x, y in pts:
        c.px(x, y, 'o')
    ins = _inner(pts)
    for x, y in ins:
        if (x, y) in rib:
            col = 'L'
        elif (x - 1, y) not in ins or (x, y - 1) not in ins:
            col = 'L'
        elif (x + 1, y) not in ins or (x, y + 1) not in ins:
            col = 'K'
        else:
            col = 'G'
        c.px(x, y, col)
    return ins


def ellipse_pts(cx, cy, rx, ry):
    return {(x, y) for y in range(cy - ry, cy + ry + 1) for x in range(cx - rx, cx + rx + 1)
            if ((x - cx) / (rx + 0.5)) ** 2 + ((y - cy) / (ry + 0.5)) ** 2 <= 1}


